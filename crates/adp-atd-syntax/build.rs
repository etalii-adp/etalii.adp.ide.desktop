//! Builds ATD's grammar into static tables (etalii.adp spec 035, T039): from `ATD_SPEC_DIR/grammar` when the variable
//! is set (an etalii.adp branch built together with this one), else from the vendored copy.

use std::fmt::Write as _;
use std::path::PathBuf;

use adp_atd_grammar::{Action, TerminalKind};

fn main() {
    println!("cargo:rerun-if-env-changed=ATD_SPEC_DIR");
    let spec = match std::env::var_os("ATD_SPEC_DIR") {
        Some(dir) => PathBuf::from(dir),
        None => PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap())
            .join("../../vendor/etalii.adp/specifications/atd"),
    };
    let grammar_dir = spec.join("grammar");
    for module in [
        "atd", "core", "cel", "script", "canvas", "form", "text", "binding", "notation",
    ] {
        println!(
            "cargo:rerun-if-changed={}",
            grammar_dir.join(format!("{module}.lark")).display()
        );
    }
    let built = adp_atd_grammar::build_dir(&grammar_dir, "atd", "description")
        .unwrap_or_else(|e| panic!("ATD's grammar does not build: {e}"));
    let grammar = &built.grammar;
    let mut terminals: Vec<String> = grammar.terminals.iter().map(|t| t.name.clone()).collect();
    terminals.push("$END".into());
    let mut nonterminals: Vec<String> = grammar.rules.iter().map(|r| r.lhs.clone()).collect();
    nonterminals.sort();
    nonterminals.dedup();
    let nonterminal = |name: &str| nonterminals.binary_search_by(|n| n.as_str().cmp(name)).unwrap();
    let terminal = |name: &str| terminals.iter().position(|t| t == name).unwrap();
    let mut out = String::new();
    writeln!(out, "// Generated by build.rs from ATD's grammar; do not edit.").unwrap();
    writeln!(out, "pub const VERSION: &str = \"0.1\";").unwrap();
    writeln!(out, "pub static TERMINALS: &[TerminalInfo] = &[").unwrap();
    for t in &grammar.terminals {
        let keyword = t.kind == TerminalKind::String && t.value.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        writeln!(
            out,
            "    TerminalInfo {{ name: {:?}, pattern: {}, value: {:?}, priority: {}, ignored: {}, keyword: {} }},",
            t.name,
            t.kind == TerminalKind::Pattern,
            t.value,
            t.priority,
            grammar.ignore.contains(&t.name),
            keyword
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub const END: u16 = {};", terminals.len() - 1).unwrap();
    writeln!(out, "pub static NONTERMINALS: &[&str] = &{nonterminals:?};").unwrap();
    writeln!(out, "pub static RULES: &[RuleInfo] = &[").unwrap();
    for rule in &grammar.rules {
        let name = rule.alias.clone().unwrap_or_else(|| rule.lhs.clone());
        writeln!(
            out,
            "    RuleInfo {{ lhs: {}, len: {}, name: {:?}, helper: {}, inline: {} }},",
            nonterminal(&rule.lhs),
            rule.rhs.len(),
            name,
            rule.lhs.ends_with(")+"),
            rule.alias.is_none() && grammar.inline.contains(&rule.lhs)
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    // Actions: per state, (terminal, code): shift n as n, reduce r as -(r + 1), accept as i32::MIN.
    writeln!(out, "pub static ACTIONS: &[&[(u16, i32)]] = &[").unwrap();
    for state in &built.tables.states {
        let mut entries = Vec::new();
        for (t, action) in &state.actions {
            let code = match action {
                Action::Shift(n) => *n as i32,
                Action::Reduce(r) => -(*r as i32) - 1,
                Action::Accept => i32::MIN,
            };
            entries.push((terminal(t), code));
        }
        entries.sort();
        let entries: Vec<String> = entries.iter().map(|(t, code)| format!("({t}, {code})")).collect();
        writeln!(out, "    &[{}],", entries.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static GOTOS: &[&[(u16, u16)]] = &[").unwrap();
    for state in &built.tables.states {
        let mut entries: Vec<(usize, usize)> = state.gotos.iter().map(|(n, s)| (nonterminal(n), *s)).collect();
        entries.sort();
        let entries: Vec<String> = entries.iter().map(|(n, s)| format!("({n}, {s})")).collect();
        writeln!(out, "    &[{}],", entries.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("tables.rs");
    std::fs::write(path, out).unwrap();
}
