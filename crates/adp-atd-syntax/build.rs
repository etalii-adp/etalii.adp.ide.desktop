//! Embeds ATD's grammar (etalii.adp spec 035, T165): its modules' texts, which `etalii-lark` builds into the parser
//! when it is first used, so that nothing is read at run time and the WebAssembly build reads nothing either. From
//! `ATD_SPEC_DIR/grammar` when the variable is set (an etalii.adp branch built together with this one), else from the
//! vendored copy.

use std::fmt::Write as _;
use std::path::PathBuf;

const MODULES: [&str; 9] = [
    "atd", "core", "cel", "script", "canvas", "form", "text", "binding", "notation",
];

fn main() {
    println!("cargo:rerun-if-env-changed=ATD_SPEC_DIR");
    let spec = match std::env::var_os("ATD_SPEC_DIR") {
        Some(dir) => PathBuf::from(dir),
        None => PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap())
            .join("../../vendor/etalii.adp/specifications/atd"),
    };
    let grammar_dir = spec.join("grammar");
    let mut out = String::new();
    writeln!(out, "// Generated by build.rs from ATD's grammar; do not edit.").unwrap();
    writeln!(out, "pub const VERSION: &str = \"0.1\";").unwrap();
    writeln!(out, "pub static MODULES: &[(&str, &str)] = &[").unwrap();
    for module in MODULES {
        let path = grammar_dir.join(format!("{module}.lark"));
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        writeln!(out, "    ({module:?}, {text:?}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("grammar.rs");
    std::fs::write(path, out).unwrap();
}
